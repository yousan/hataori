// The empty environment protocol, pinned Direct catalog and actual tools were
// checked together. A different CLI, model or catalog needs a new real capture.
const confinedVersion = "codex-cli 0.163.0"
const confinedModel = "gpt-6-luna"
const confinedHome = "codex-confined"
const confinedInstructions = confinedHome + "/instructions.txt"

//go:embed model_catalog.json
var confinedCatalog []byte

const confinedCatalogFile = confinedHome + "/model-catalog.json"
const confinedInstructionsHeader = "# Generated by hataori: confined Codex instructions.\n"

var confinedFeatures = []string{"shell_tool", "unified_exec", "multi_agent", "goals", "sleep_tool", "apps", "plugins", "hooks", "browser_use", "computer_use", "image_generation", "in_app_local_automation", "memories", "shell_snapshot", "view_image", "skill_search", "stable_environment_tools", "daemon_auto_start", "code_mode", "code_mode_only", "code_mode_host"}

const confinedInputNote = "In input, (at) stands for @ and (dollar) stands for $. These characters are neutralized before input reaches the CLI so it cannot attach resources or invoke skills. Restore them only in your own answers or arguments to the supplied tools."

// confinedLaunch uses no native environment on every turn (codec.go). The
// outer Linux namespace isolates mutable CLI state and exposes existing CLI
// authentication read-only: a refresh cannot overwrite the original authentication file. Only
// explicit runtime paths and supplied MCP commands/absolute arguments are
// mounted. No authentication bytes are read or copied by hataori.
func (a *Adapter) confinedLaunch(spec agent.Spec) (agent.Launch, error) {
	refuse := func(why string) (agent.Launch, error) {
		return agent.Launch{}, fmt.Errorf("%s: confined launch refused: %s", Name, why)
	}
	if runtime.GOOS != "linux" {
		return refuse("only the captured Linux launch is supported")
	}
	if spec.Model != confinedModel {
		return refuse("requires the verified model " + confinedModel)
	}
	if !filepath.IsAbs(spec.StateDir) || spec.StateDir == spec.Dir {
		return refuse("requires a separate absolute state directory")
	}
	bwrap, err := exec.LookPath("bwrap")
	if err != nil {
		return refuse("bubblewrap is required for configuration and authentication isolation")
	}
	cli, err := exec.LookPath(a.command)
	if err != nil {
		return refuse("Codex executable is unavailable")
	}
	cli, err = filepath.EvalSymlinks(cli)
	if err != nil {
		return refuse("cannot resolve Codex executable")
	}
	version, _, err := a.run(context.Background(), spec, "--version")
	if err != nil || strings.TrimSpace(string(version)) != confinedVersion {
		return refuse("requires the verified CLI " + confinedVersion)
	}

	_, status, err := a.run(context.Background(), spec, "login", "status")
	if err != nil || strings.TrimSpace(string(status)) != "Logged in using ChatGPT" {
		return refuse("existing ChatGPT CLI authentication is required; no API-key fallback is used")
	}
	var userHome, loginHome string
	for _, kv := range a.sessionEnv(spec) {
		if v, ok := strings.CutPrefix(kv, "HOME="); ok {
			userHome = v
		}
		if v, ok := strings.CutPrefix(kv, "CODEX_HOME="); ok {
			loginHome = v
		}
	}
	if loginHome == "" {
		loginHome = filepath.Join(userHome, ".codex")
	}
	if !filepath.IsAbs(loginHome) {
		return refuse("existing CLI authentication directory must be absolute")
	}
	auth := filepath.Join(loginHome, "auth.json")
	info, err := os.Stat(auth)
	if err != nil || !info.Mode().IsRegular() {
		return refuse("existing file-based CLI authentication is required; no login or fallback is attempted")
	}

	resolvedState, err := filepath.EvalSymlinks(spec.StateDir)
	if err != nil || resolvedState != filepath.Clean(spec.StateDir) {
		return refuse("state directory must exist without symlink aliases")
	}
	resolvedLogin, err := filepath.EvalSymlinks(loginHome)
	if err != nil {
		return refuse("cannot resolve existing authentication directory")
	}
	home := filepath.Join(spec.StateDir, confinedHome)
	if withinPath(home, resolvedLogin) || withinPath(resolvedLogin, home) {
		return refuse("CLI state must be separate from the existing authentication directory")
	}

	for _, path := range []string{home, filepath.Join(home, "config.toml"), filepath.Join(home, "auth.json"), filepath.Join(spec.StateDir, confinedInstructions), filepath.Join(spec.StateDir, confinedCatalogFile)} {
		info, err := os.Lstat(path)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return refuse("cannot inspect generated CLI state")
		}
		if err == nil && (path == home && !info.IsDir() || path != home && (!info.Mode().IsRegular() || info.Sys().(*syscall.Stat_t).Nlink > 1)) {
			return refuse("generated CLI state must use a directory and regular unlinked files")
		}
	}
	if data, err := os.ReadFile(filepath.Join(home, "config.toml")); err != nil && !errors.Is(err, os.ErrNotExist) {
		return refuse("cannot inspect existing generated CLI configuration")
	} else if err == nil && !strings.HasPrefix(string(data), confinedConfigHeader) {
		return refuse("refusing to overwrite an unrecognized CLI configuration")
	}
	if data, err := os.ReadFile(filepath.Join(spec.StateDir, confinedInstructions)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return refuse("cannot inspect existing generated instructions")
	} else if err == nil && !strings.HasPrefix(string(data), confinedInstructionsHeader) {
		return refuse("refusing to overwrite unrecognized instructions")
	}
	if data, err := os.ReadFile(filepath.Join(spec.StateDir, confinedCatalogFile)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return refuse("cannot inspect existing generated model catalog")
	} else if err == nil && !bytes.Equal(data, confinedCatalog) {
		return refuse("refusing to overwrite an unrecognized model catalog")
	}
	// A fresh generated config is the only user config in this namespace.
	// Untrusted scope config cannot add MCP servers, hooks, skills or tools.
	config := confinedConfigHeader + "approval_policy=\"never\"\nsandbox_mode=\"read-only\"\nweb_search=\"disabled\"\nproject_doc_max_bytes=0\ncli_auth_credentials_store=\"file\"\n"
	config += "model_catalog_json=" + tomlString(filepath.Join(spec.StateDir, confinedCatalogFile)) + "\n"
	instructions := confinedInstructionsHeader + strings.TrimSpace(confinedInputNote+"\n\n"+spec.Instructions)
	config += "[projects." + tomlString(spec.Dir) + "]\ntrust_level=\"untrusted\"\n[agents]\nmax_depth=0\n[features]\n"
	for _, f := range confinedFeatures {
		config += f + "=false\n"
	}
	config += "retain_client_developer_messages=true\n"
	servers := map[string]bool{}
	for _, s := range spec.Confine.MCP {
		if servers[s.Name] {
			return refuse("duplicate supplied MCP server name")
		}
		servers[s.Name] = true
		if s.Name == "" || len(s.Argv) == 0 {
			return refuse("each supplied MCP server needs a name and command")
		}
		command, err := exec.LookPath(s.Argv[0])
		if err != nil {
			return refuse("a supplied MCP command is unavailable")
		}
		command, err = filepath.EvalSymlinks(command)
		if err != nil {
			return refuse("cannot resolve supplied MCP command")
		}
		config += "[mcp_servers." + tomlString(s.Name) + "]\ncommand=" + tomlString(command) + "\nargs="
		args, _ := json.Marshal(append([]string{}, s.Argv[1:]...))
		config += string(args) + "\ndefault_tools_approval_mode=\"approve\"\n"
		env := s.Env
		if len(env) > 0 {
			config += "[mcp_servers." + tomlString(s.Name) + ".env]\n"
		}
		envKeys := map[string]bool{}
		for _, kv := range env {
			k, v, ok := strings.Cut(kv, "=")
			if !ok || k == "" || envKeys[k] {
				return refuse("invalid supplied MCP environment")
			}
			envKeys[k] = true
			config += tomlString(k) + "=" + tomlString(v) + "\n"
		}
	}
	argv := []string{bwrap, "--proc", "/proc", "--dev", "/dev", "--tmpfs", "/tmp"}
	mounted := map[string]bool{}
	mount := func(path string) {
		if !mounted[path] {
			argv = append(argv, "--ro-bind", path, path)
			mounted[path] = true
		}
	}
	for _, path := range []string{"/usr", "/bin", "/lib", "/lib64", "/etc/ssl", "/etc/resolv.conf", "/etc/hosts", "/etc/nsswitch.conf"} {
		if _, err := os.Stat(path); err == nil {
			mount(path)
		}
	}
	mount(filepath.Dir(cli))
	mount(spec.Dir)
	for _, s := range spec.Confine.MCP {
		command, err := exec.LookPath(s.Argv[0])
		if err != nil {
			return refuse("a supplied MCP command is unavailable")
		}
		command, err = filepath.EvalSymlinks(command)
		if err != nil {
			return refuse("cannot resolve supplied MCP command")
		}
		mount(command)
		// MCP launch arguments are trusted, supplied by the confinement provider.
		// In particular a server may need its control socket's root directory.
		for _, arg := range s.Argv[1:] {
			if filepath.IsAbs(arg) {
				if _, err := os.Stat(arg); err == nil {
					mount(arg)
				}
			}
		}
	}
	argv = append(argv, "--bind", spec.StateDir, spec.StateDir,
		"--ro-bind", auth, filepath.Join(home, "auth.json"), "--unshare-pid", "--die-with-parent", "--chdir", spec.Dir, "--clearenv")
	// Do not inherit pass_env, API keys, proxies, user config directories or
	// shell startup variables. MCP receives only its explicitly supplied env.
	env := []string{"HOME=" + home, "CODEX_HOME=" + home, "PATH=/usr/local/bin:/usr/bin:/bin", "LANG=C.UTF-8", "GIT_DIR=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null"}
	for _, kv := range env {
		k, v, _ := strings.Cut(kv, "=")
		argv = append(argv, "--setenv", k, v)
	}
	argv = append(argv, cli, "app-server")
	return agent.Launch{Argv: argv, Env: env, Files: map[string][]byte{confinedHome + "/config.toml": []byte(config), confinedInstructions: []byte(instructions), confinedCatalogFile: confinedCatalog}, Confined: true, NoWriteTools: true, NoCommands: true, NoMentions: true}, nil
}

func (c *codec) inputText(text string) string {
	if c.spec.Confine != nil {
		return strings.NewReplacer("@", "(at)", "$", "(dollar)").Replace(text)
	}
	return text
}

func (c *codec) textInput(text string) map[string]any {
	input := map[string]any{"type": "text", "text": c.inputText(text)}
	if c.spec.Confine != nil {
		input["text_elements"] = []any{}
	}
	return input
}

const confinedConfigHeader = "# Generated by hataori for a confined Codex launch.\n"

func withinPath(path, parent string) bool {
	rel, err := filepath.Rel(parent, path)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

// readConfinedInstructions never reads credentials. Invalid generated state
// becomes a fail-closed codec without startup requests, rather than a launch
// with incomplete supervisor instructions.
func readConfinedInstructions(state string) string {
	path := filepath.Join(state, confinedInstructions)
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || info.Sys().(*syscall.Stat_t).Nlink > 1 {
		return ""
	}
	data, err := os.ReadFile(path)
	if err != nil || !strings.HasPrefix(string(data), confinedInstructionsHeader) {
		return ""
	}
	return strings.TrimPrefix(string(data), confinedInstructionsHeader)
}
