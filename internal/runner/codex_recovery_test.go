// These are real CLI responses, delivered by a disposable pipe peer.
// No CLI, authentication, inference, terminal or provider is used. The runner's
// real pipe host, commit, follow, warmIO, polling and act paths are exercised.
func codexThreadResponse(t *testing.T, scenario string) ([]byte, string) {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("../agent/codex/testdata/0.163.0", scenario, "wire.jsonl"))
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range bytes.Split(b, []byte("\n")) {
		var row struct {
			Dir string          `json:"dir"`
			Msg json.RawMessage `json:"msg"`
		}
		var msg struct {
			Result struct {
				Thread struct{ ID string } `json:"thread"`
			} `json:"result"`
		}
		if json.Unmarshal(line, &row) == nil && row.Dir == "recv" && json.Unmarshal(row.Msg, &msg) == nil && msg.Result.Thread.ID != "" {
			return row.Msg, msg.Result.Thread.ID
		}
	}
	t.Fatal("missing captured thread response")
	return nil, ""
}

func TestConfinedCodexReconnectRecoversInstructionGate(t *testing.T) {
	python, err := exec.LookPath("python3")
	if err != nil {
		t.Fatal(err)
	}
	peer, err := filepath.Abs("testdata/codex_recovery.py")
	if err != nil {
		t.Fatal(err)
	}
	ack, err := os.ReadFile("../agent/codex/testdata/0.163.0/supervisor_actual/instruction-ack.json")
	if err != nil {
		t.Fatal(err)
	}
	ad, err := codex.New(nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, scenario := range []string{"start", "resume"} {
		thread, nativeID := codexThreadResponse(t, scenario)
		for _, boundary := range []string{"not_sent", "ack_uncommitted", "ack_committed", "twice", "malformed", "refused"} {
			t.Run(scenario+"/"+boundary, func(t *testing.T) {
				x := storedReader(t, nil)
				r := x.r
				r.Machine = &session.Machine{Store: r.Store}
				r.Host = host.Command{Path: os.Args[0], Args: []string{"role", "host"}}
				r.Poll, r.StartTimeout, r.IdlePeriod = 20*time.Millisecond, 30*time.Second, time.Hour
				spec := agent.Spec{StateDir: x.lv.dir, Model: "gpt-6-luna", Confine: &agent.Confinement{}}
				if scenario == "resume" {
					spec.ResumeID = nativeID
				}
				instructions := filepath.Join(spec.StateDir, "codex-confined", "instructions.txt")
				if err := os.MkdirAll(filepath.Dir(instructions), 0700); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(instructions, []byte("# Generated by hataori: confined Codex instructions.\ncurrent-recovery-instructions"), 0600); err != nil {
					t.Fatal(err)
				}
				x.lv.codec, x.lv.spec = ad.NewCodec(spec), spec
				x.lv.codec.Open() // the original daemon opened this process
				fi, _ := json.Marshal(firstInput{Principal: "owner", Key: "recovery", Text: "one-recovery-input", NoInput: boundary == "ack_committed"})
				if _, err := r.Store.DB.Exec(`UPDATE sessions SET state='creating', first_input=?, created_at=? WHERE id=1`, string(fi), time.Now().UnixMilli()); err != nil {
					t.Fatal(err)
				}
				if _, err := r.Store.DB.Exec(`UPDATE threads SET state='creating', confined=1 WHERE id=1`); err != nil {
					t.Fatal(err)
				}
				requestLog := filepath.Join(spec.StateDir, "fixture-requests.jsonl")
				w, err := r.own().Start(context.Background(), spec.StateDir, holder.Spec{Argv: []string{python, "-u", peer, requestLog}, Dir: spec.StateDir,
					Env: []string{"PATH=/usr/bin:/bin", "LANG=C.UTF-8"}})
				if err != nil {
					t.Fatal(err)
				}
				t.Cleanup(func() {
					r.Close() // leave the owned fixture host until its explicit cleanup
					r.own().Stop(context.Background(), w, time.Second, time.Second)
				})
				log := func() []byte {
					b, _ := os.ReadFile(filepath.Join(spec.StateDir, host.EventsFile))
					return b
				}
				write := func(b []byte) {
					t.Helper()
					line := append(bytes.TrimSpace(b), '\n')
					wrapped, _ := json.Marshal(map[string]string{"fixture_response": string(bytes.TrimSpace(b))})
					if err := r.own().Write(context.Background(), w, [][]byte{append(wrapped, '\n')}); err != nil {
						t.Fatal(err)
					}
					waitFor(t, "fixture response", 3*time.Second, func() bool { return bytes.Contains(log(), line) })
				}
				requests := func(method string) [][]byte {
					var out [][]byte
					data, _ := os.ReadFile(requestLog)
					for _, line := range bytes.Split(data, []byte("\n")) {
						var m struct{ Method string }
						if json.Unmarshal(line, &m) == nil && m.Method == method {
							out = append(out, line)
						}
					}
					return out
				}
				commit := func() batch {
					t.Helper()
					b := r.read(x.lv)
					if b.err != nil {
						t.Fatal(b.err)
					}
					if _, err := r.commit(x.lv, b); err != nil {
						t.Fatal(err)
					}
					x.lv.offset = b.offset
					return b
				}
				write(thread)
				b := commit() // crash boundary: offsets durable, injection not acted
				if len(b.actions) != 1 || len(b.actions[0].Write) != 1 {
					t.Fatal("missing single captured-response injection")
				}
				if boundary == "ack_uncommitted" || boundary == "ack_committed" {
					if err := r.act(x.lv, b.actions[0]); err != nil {
						t.Fatal(err)
					}
					write(ack)
					if boundary == "ack_committed" {
						commit()
					}
				}
				follow := func() {
					t.Helper()
					if err := r.follow(1, ad, spec, reconnect); err != nil {
						t.Fatal(err)
					}
				}
				follow()
				if boundary != "ack_committed" {
					waitFor(t, "recovered instruction request", 4*time.Second, func() bool { return len(requests("thread/inject_items")) == 1 })
				}
				if boundary == "twice" {
					r.Close()
					follow()
					waitFor(t, "second reconnect retry", 4*time.Second, func() bool { return len(requests("thread/inject_items")) == 2 })
					got := requests("thread/inject_items")
					if !bytes.Equal(got[0], got[1]) {
						t.Fatal("retry changed trusted instruction bytes or correlation")
					}
				}
				if boundary != "ack_uncommitted" && boundary != "ack_committed" {
					var state string
					r.Store.DB.QueryRow(`SELECT state FROM sessions WHERE id=1`).Scan(&state)
					if state != string(control.Creating) || len(requests("turn/start")) != 0 {
						t.Fatal("readiness gate opened before instruction acknowledgement")
					}
					response := ack
					if boundary == "malformed" || boundary == "refused" {
						var m map[string]any
						json.Unmarshal(ack, &m)
						m["result"] = nil
						if boundary == "refused" {
							// The envelope/code is the captured no-rollout refusal.
							capture, _ := os.ReadFile("../agent/codex/testdata/0.163.0/resume_unknown/wire.jsonl")
							for _, line := range bytes.Split(capture, []byte("\n")) {
								var row struct{ Msg map[string]any }
								if json.Unmarshal(line, &row) == nil && row.Msg["error"] != nil {
									delete(m, "result")
									m["error"] = row.Msg["error"]
									break
								}
							}
						}
						response, _ = json.Marshal(m)
					}
					write(response)
				}
				expectTurn := boundary != "ack_committed" && boundary != "malformed" && boundary != "refused"
				if expectTurn {
					waitFor(t, "one queued turn", 3*time.Second, func() bool { return len(requests("turn/start")) == 1 })
				} else if boundary != "ack_committed" {
					waitFor(t, "closed instruction gate", 3*time.Second, func() bool {
						var state string
						r.Store.DB.QueryRow(`SELECT state FROM sessions WHERE id=1`).Scan(&state)
						return state == string(control.Failed)
					})
				}
				// Cross another periodic tick: no injection retry after an ack,
				// no queued turn before/refused by the gate, no duplicate input.
				time.Sleep(1100 * time.Millisecond)
				wantTurns := 0
				if expectTurn {
					wantTurns = 1
				}
				if len(requests("turn/start")) != wantTurns {
					t.Fatal("queued input lost or duplicated")
				}
				wantInjections := 1
				if boundary == "twice" {
					wantInjections = 2
				}
				if len(requests("thread/inject_items")) != wantInjections {
					t.Fatal("instruction injection replayed after acknowledgement")
				}
				if expectTurn || boundary == "ack_committed" {
					var id string
					r.Store.DB.QueryRow(`SELECT agent_session_id FROM sessions WHERE id=1`).Scan(&id)
					if id != nativeID {
						t.Fatal("reconnect changed the native conversation")
					}
				}
			})
		}
	}
}
