#!/usr/bin/env python3
"""Regenerate approval-text Unicode tables from pinned Unicode 18.0 data."""
import argparse
import hashlib
from pathlib import Path
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parent
SOURCES = {
    "emoji-test.txt": ("emoji/emoji-test.txt", "8f3735cda1f92a779d78af67cf86066bb1f07143dc22f2ac29394d9bc57ab21a"),
    "emoji-variation-sequences.txt": ("ucd/emoji/emoji-variation-sequences.txt", "ff1707564aa1f1b2fcf4ec92d609d4cb26940bc0d4dcf07f5328ad6879e84da3"),
    "DerivedCoreProperties.txt": ("ucd/DerivedCoreProperties.txt", "09c928886a178fcafd93c29e4bd59073a058e5a100b716d425cb563ab50f68c9"),
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--data-dir", type=Path, help="use previously downloaded source files")
args = parser.parse_args()
files = {}
for name, (path, digest) in SOURCES.items():
    data = (args.data_dir / name).read_bytes() if args.data_dir else urllib.request.urlopen(
        "https://www.unicode.org/Public/18.0.0/" + path, timeout=30).read()
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit("Unicode source checksum changed: " + name)
    files[name] = data.decode("utf-8")

ranges = []
for line in files["DerivedCoreProperties.txt"].splitlines():
    fields = line.split("#", 1)[0].split(";")
    if len(fields) < 2 or fields[1].strip() != "Default_Ignorable_Code_Point":
        continue
    bounds = fields[0].strip().split("..")
    ranges.append((int(bounds[0], 16), int(bounds[-1], 16)))
ranges.sort()

def ignorable(code):
    return any(lo <= code <= hi for lo, hi in ranges)

sequences = set()
for name in ("emoji-test.txt", "emoji-variation-sequences.txt"):
    for line in files[name].splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) < 2 or not fields[0].strip():
            continue
        codes = tuple(int(x, 16) for x in fields[0].split())
        if not any(c in (0x200D, 0xFE0F) for c in codes):
            continue
        if any(ignorable(c) and c not in (0x200D, 0xFE0F) for c in codes):
            continue
        sequences.add(codes)

def quoted(codes):
    return '"' + ''.join(('\\u%04x' if c <= 0xffff else '\\U%08x') % c for c in codes) + '"'

out = ["// Code generated by generate.py from Unicode 18.0; DO NOT EDIT.",
       "// Unicode data is used under the license in LICENSE.txt.", "package approvaltext", "",
       "var emojiSequences = map[rune][]string{"]
for first in sorted(set(c[0] for c in sequences)):
    out.append("0x%x: {" % first)
    for sequence in sorted((c for c in sequences if c[0] == first), key=lambda c: (-len(c), c)):
        out.append(quoted(sequence) + ",")
    out.append("},")
out.extend(["}", "", "var defaultIgnorable = [][2]rune{"])
out.extend("{0x%x, 0x%x}," % bounds for bounds in ranges)
out.extend(["}", ""])
(ROOT / "unicode_generated.go").write_text('\n'.join(out))
subprocess.run(["gofmt", "-w", str(ROOT / "unicode_generated.go")], check=True)
(ROOT / "testdata/18.0/emoji-test.txt").write_text(files["emoji-test.txt"])
print("Generated", len(sequences), "listed emoji sequences and", len(ranges), "ignorable ranges")
